//! План работ самого Slipway, записанный по его же методологии.
//!
//! Правило плана (решение 5): единицы работы заводятся только на текущие
//! срезы, не больше пяти на срез. Будущее живёт исходами направлений и
//! инвариантами спецификаций, а не файлами, заведёнными впрок.
//!
//! Состояния у записей нет: по инварианту 3 состояние — свёртка журнала.
//! Журнала пока нет (работа 5), и до него сделанное восстанавливается из
//! истории git по трейлеру `Slipway-Work: w0001` в сообщении коммита.

include!(concat!(env!("OUT_DIR"), "/plan.rs"));

#[cfg(test)]
mod tests {
    use super::*;

    /// Не больше пяти единиц работы на срез. Сила — по требованию: это тест,
    /// а не тип, и держится он тем, что тесты запускают.
    #[test]
    fn work_is_planned_within_wip() {
        for s in ALL_SLICES {
            let n = ALL_WORK.iter().filter(|w| w.slice.index() == s.id).count();
            assert!(n <= 5, "срез «{}» несёт {n} единиц работы", s.title.as_str());
        }
    }
}
