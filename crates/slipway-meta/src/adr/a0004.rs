slipway_knowledge::adr!(4,
    title: "Правило заменяется формой записи: невыразимость вместо валидации",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Knowledge)],
    context: r#"
        Правило можно попросить соблюдать, можно проверять, а можно устроить
        так, что нарушение не набирается. Первое держится памятью, второе —
        тем, что проверку не отключили, у третьего выключателя нет вовсе.

        Приём известен в типизированном программировании под именами
        «make illegal states unrepresentable», «parse, don't validate» и
        «correct by construction».
    "#,
    decision: r#"
        Всюду, где возможно, правило переводится в систему типов: ссылка
        становится путём к константе, непустота выражается типом,
        взаимозависимые поля объединяются в один вариант, признак,
        выводимый из варианта, не хранится отдельно.

        Валидатору остаётся то, что типами не выражается: двусторонность
        графа замещений, статус документа на момент ссылки, покрытие
        гейтами, квоты, легальность переходов журнала, допуск исполнителя.
    "#,
    trade_offs: &[
        "Плюс: у типа нет выключателя, в отличие от проверки",
        "Плюс: валидатор сокращается, меньше кода — меньше ошибок в нём",
        "Минус: типы ловят рассогласование, но не неверное по существу",
        "Минус: изменение схемы ломает существующие записи сильнее, чем изменение проверки",
    ],
    constraints: &[
        "Правило, выразимое типом, не должно проверяться валидатором.",
        "Граница приёма называется вместе с ним: рассогласование ловится, глупость нет.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[],
);
