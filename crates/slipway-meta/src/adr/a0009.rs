use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(9,
    title: "Репозиторий методологии не содержит внешних артефактов",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Methodology)],
    context: r#"
        Методология выросла из практики конкретных проектов, и их следы
        остались в тексте: имена, номера их документов, цифры их
        ретроспектив, названия их подсистем в примерах. Для проекта
        методологии это внешние артефакты: читатель не может их проверить,
        а публикация раскрыла бы чужую внутреннюю информацию.

        Большая часть таких следов была в markdown-спецификации, перенос
        которой в реестр уже решён (решение 6).
    "#,
    decision: r#"
        Текст, код и примеры методологии не называют проекты, на практике
        которых методология выросла или обкатывается, и не цитируют их
        документы. Норма, пришедшая из практики, называет породивший её отказ
        своими словами. Ссылки на публичные источники — стандарты, книги,
        открытые проекты — допустимы: их читатель может проверить.

        Каталог spec/ и файл ревью удаляются до завершения переноса.
        Публикуемая история начинается с чистого коммита; прежняя история, где
        лежит текст спецификации, хранится локально и служит источником
        переноса. Перенос не копирует текст, а переписывает его по этому
        правилу.
    "#,
    trade_offs: &[
        "Плюс: репозиторий можно публиковать без чужой внутренней информации",
        "Плюс: норма держится на названном отказе, а не на авторитете источника",
        "Минус: до переноса нормативный текст доступен только в локальной прежней истории",
        "Минус: отказ без имени источника нельзя перепроверить по первоисточнику",
        "Минус: поштучная история первых дней остаётся только в локальном архиве",
    ],
    constraints: &[
        "Проверка на пути коммита отвергает строки с именами из локального списка внешних проектов; список хранится в каталоге git, а не в репозитории.",
        "Без локального списка проверка сообщает, что не выполнялась, а не проходит молча.",
        "Публикуется только история, начатая с чистого коммита; прежняя история не публикуется ни веткой, ни тегом.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[],
);
