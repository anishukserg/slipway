slipway_knowledge::adr!(8,
    title: "Правила коммитов: форма сообщения, основание из плана, явные пути, проверка дерева коммита",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r#"
        Работа обязана иметь основание, готовность — доказательство. До
        журнала единственная запись о сделанном — история git, и держится она
        ровно настолько, насколько дисциплинированы коммиты.

        Известные отказы коммитов при работе агентов: словарь типов в теме
        расползается синонимами, если форма не проверяется; `git add -A` в
        общем дереве забирает чужие изменения; проверка, спрятанная за «если
        инструмент установлен», молча выключается; хук печатает сотни строк,
        из которых нужна одна; проверка рабочего дерева при частичном коммите
        подтверждает не то дерево, которое уходит в историю.
    "#,
    decision: r#"
        Тема — `[ТИП](область): суть`: тип из закрытого набора FEAT, FIX,
        REFACTOR, TEST, DOCS, ADR, PLAN, CHORE; область — значения оси
        подсистем в нижнем регистре через запятую; не длиннее 72 символов, без
        точки в конце. Каждый коммит несёт трейлер `Slipway-Work: wNNNN`, и
        единица работы обязана существовать в дереве этого коммита.

        Коммит делается `tools/commit.sh`: сообщение проверяется до блокировки
        и хуков, пути перечисляются явно, параллельный коммит ждёт блокировку,
        вердикт — последней строкой `COMMIT OK <sha>` или
        `COMMIT REFUSED: <причина>`; «отвергнут» и «нечего коммитить» имеют
        разные коды.

        Хук pre-commit выгружает дерево коммита и гоняет на нём калитку
        `tools/gate.sh`: внешние имена по локальному списку, сборку всех целей
        с константными проверками реестров, тесты и атаки с полом по числу
        прошедших doctest. Отсутствующий инструмент — отказ, а не пропуск;
        отсутствующий список внешних имён — шаг, названный невыполненным.
        Изменение самих правил проходит их самотест.
    "#,
    trade_offs: &[
        "Плюс: основание коммита проверяется по дереву коммита, а не по памяти автора",
        "Плюс: частичный коммит проверяется тем деревом, которое уходит в историю",
        "Минус: калитка на каждом коммите стоит секунд сборки и тестов; бюджет — 60 секунд на прогретом кэше",
        "Минус: хуки обходятся флагом --no-verify, а удалённого CI у репозитория нет",
        "Минус: форматирование и clippy не входят в калитку — в установленном тулчейне этих компонентов нет",
    ],
    constraints: &[
        "Без явных путей коммит не делается: `git add -A` без путей, `git add .` и `git commit -a` запрещены.",
        "`--amend`, переписывание истории и `--no-verify` — только по явной просьбе владельца репозитория.",
        "Калитка, превысившая бюджет, делится на слой коммита и слой закрытия работы, а не выключается.",
        "Пол числа doctest в калитке только растёт; понижение — изменение правила с ревью.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002],
);
