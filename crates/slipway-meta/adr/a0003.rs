use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(3,
    title: "Валидатор — бинарник, линкующий реестр, а не build.rs",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Knowledge), taxon!(Subsystem, Work)],
    context: r#"
        Та же ловушка, что погубила схему с inventory (см. решение 1):
        build.rs видит только свои build-зависимости и потому не может
        исполнять правила над реестром, который собирается позже.

        Кроме того, включение валидатора в граф сборки означало бы, что
        каждое изменение статуса задачи инвалидирует продуктовый бинарник.
    "#,
    decision: r#"
        Правила, не выразимые типами, исполняет обычный бинарник, линкующий
        реестр как библиотеку. Точка принуждения — хук коммита плюс
        обязательный CI на защищённой ветке.

        Это слабее компилятора ровно на одно: локальный хук обходится флагом
        --no-verify, поэтому парный CI обязателен. Защита ветки остаётся
        организационным требованием вне методологии.
    "#,
    trade_offs: &[
        "Плюс: сборка продукта не платит за методологию",
        "Плюс: правила пишутся обычным Rust, а не генерацией compile_error",
        "Минус: слабее компилятора — нужен CI на защищённой ветке",
    ],
    constraints: &["Утверждение «проверяется компилятором» допустимо только для проверок из перечня части VI §3.1.1."],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[],
);
