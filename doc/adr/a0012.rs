use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(12,
    title: "Stable-тулчейн; коды ошибок атак сверяются под RUSTC_BOOTSTRAP",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r"
        Разработка шла на nightly без даты: любой rustup update менял
        компилятор, clippy и rustfmt, и тот же коммит мог покраснеть без
        изменений в коде. Единственной причиной nightly были атаки — doctest
        compile_fail с кодом ошибки.

        Опыт показал цену перехода в лоб. На stable 1.98.1 и 1.83.0 атака,
        объявившая E0080, а давшая E0308, проходит: rustdoc сверяет коды
        ошибок только в nightly-режиме, и без него атака зелёная на любой
        ошибке компиляции, включая опечатку. На nightly и на stable с
        RUSTC_BOOTSTRAP=1 та же атака падает.

        Рассматривались: nightly с датой только для шага атак — второй
        тулчейн, атаки проверяет не тот компилятор, которым собирается проект,
        а на минимальной версии коды не сверяются вовсе; trybuild — эталоны
        полного вывода компилятора, новые зависимости и переписывание эталонов
        при каждом обновлении компилятора; атаки без сверки кодов — вакуумный
        зелёный, показанный опытом.
    ",
    decision: r"
        Тулчейн разработки — stable с точной версией в rust-toolchain.toml.
        Смена версии — отдельный коммит через калитку.

        Атаки выполняются отдельным шагом калитки: cargo test --doc под
        RUSTC_BOOTSTRAP=1 в собственном каталоге сборки — переменная меняет
        отпечаток сборки зависимостей и сбрасывала бы кэш остальных шагов.
        Перед атаками калитка проверяет сам механизм: пробная атака с неверным
        кодом обязана упасть, а с верным — пройти. Перестанет rustdoc сверять
        коды — калитка откажет, а не пропустит атаки вакуумно.

        Переменная не открывает нестабильных возможностей: lint
        unstable_features запрещён для всех крейтов рабочего пространства, а
        doctest получают тот же запрет атрибутом doc(test(attr(...))) в корне
        каждого крейта — lints манифеста на doctest не распространяются.

        Минимальная версия из rust-version рабочего пространства проверяется
        той же калиткой: сборка всех целей и атаки со сверкой кодов. Обещанная
        потребителям невыразимость проверяется на обещанном им компиляторе.
    ",
    trade_offs: &[
        "Плюс: тулчейн закреплён версией, и сборка воспроизводима между днями",
        "Плюс: атаки проверяет тот же компилятор, которым собирается проект, и минимальный обещанный",
        "Плюс: сломанная сверка кодов — отказ калитки, а не вакуумный зелёный",
        "Минус: RUSTC_BOOTSTRAP — внутренний переключатель компилятора, его поведение Rust не гарантирует; держится пробной атакой",
        "Минус: калитке нужны два установленных тулчейна и отдельные каталоги сборки — больше места и холодная сборка при смене версии",
        "Минус: новый крейт без атрибута doc(test(attr(...))) в корне пропустит #![feature] в своих doctest; атрибут не принуждается",
    ],
    constraints: &[
        "RUSTC_BOOTSTRAP выставляется только в шагах атак и пробы, не в окружении разработки и не в сборке.",
        "Атаки не считаются пройденными, если в той же калитке не прошла пробная атака.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002],
);
