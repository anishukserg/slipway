slipway_knowledge::adr!(18,
    title: "Путь изменений в master публичного репозитория: калитка в CI, перенос внешних pull request, приватные сообщения об уязвимостях",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r"
        Репозиторий опубликован на GitHub, а калитка исполнялась только хуками
        на машине сопровождающего. Хук обходится одним флагом, а правка на
        сайте, коммит без установленных хуков и слияние кнопкой не проходят
        через хуки вовсе. GUARANTEES.md называет CI и защищённую ветку внешним
        требованием методологии; у самого Slipway их не было.

        Внешний pull request не может пройти правила коммитов: трейлер
        основания ссылается на работу из плана, который ведёт сопровождающий.
        Кнопки слияния GitHub либо создают коммит слияния без трейлера, либо —
        squash и rebase — дают коммитам новые хэши, на которые не ссылается
        журнал.

        Работа 6 исследует, что такое проверка на пути в основную ветку и чем
        её вердикт независим от автора. Это решение её не закрывает: оно
        переносит существующую калитку на удалённого исполнителя.

        Рассматривались: сборка cargo-deny из исходников в каждом прогоне —
        минуты компиляции на каждый push; сторонние actions для тулчейна и
        инструментов — ещё одна цепочка доверия; обязательный pull request с
        обязательной проверкой уже сейчас — прямая запись в master, которой
        ведётся работа, стала бы невозможной до итога работы 6.
    ",
    decision: r"
        CI — workflow gate на GitHub Actions: push в master, pull request в
        master и ручной запуск. Он выгружает всю историю, ставит тулчейн из
        rust-toolchain.toml и минимальную версию из rust-version, ставит
        cargo-deny из выпущенного архива с закреплённой версией и контрольной
        суммой, загружает базу уязвимостей и выполняет cargo slipway gate — те
        же шаги, что у pre-commit. Затем cargo slipway msg-check --range
        проверяет сообщение каждого коммита диапазона по дереву этого коммита:
        у push — от прежней вершины до новой, у pull request — от базы до
        головы.

        Workflow получает только право чтения содержимого. Actions — только
        GitHub, закреплены полным хэшем коммита. Список внешних имён хранится
        в секрете SLIPWAY_EXTERNAL_NAMES, записывается в каталог git перед
        калиткой, и каждое имя маскируется в журнале прогона. Pull request из
        форка секрета не получает, и шаг внешних имён у него не выполняется.

        Внешний pull request — предложение. Сопровождающий переносит изменение
        коммитом по правилам решения 8 с автором предложения в трейлере
        Co-authored-by и закрывает pull request ссылкой на коммит; кнопками
        слияния GitHub pull request не сливаются.

        Об уязвимостях сообщают приватно — частным сообщением об уязвимости
        GitHub, не в issues. Порядок участия и сообщения об уязвимостях
        описывают CONTRIBUTING.md и SECURITY.md в корне.
    ",
    trade_offs: &[
        "Плюс: калитка исполняется не только на машине автора — правка на сайте и коммит без хуков видны в CI",
        "Плюс: коммит без основания на пути в master назван хэшем",
        "Плюс: внешние имена проверяются в CI и не публикуются",
        "Минус: при прямой записи в master CI обнаруживает нарушение после записи, а не предотвращает её — это остаётся за защитой ветки и работой 6",
        "Минус: каждое внешнее изменение переносит сопровождающий — узкое место на нём",
        "Минус: у pull request из форка шаг внешних имён не выполняется",
        "Минус: прогон без кэша собирает рабочее пространство целиком",
    ],
    constraints: &[
        "Смена версии cargo-deny меняет версию и контрольную сумму в workflow одним коммитом.",
        "Сторонний action появляется только отдельным решением.",
        "Коммиты, созданные кнопками слияния GitHub, в master не попадают.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002],
);
