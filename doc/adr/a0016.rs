use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(16,
    title: "Порождённый код реестра держит строгий профиль lints продукта",
    status: DocStatus::Active,
    subsystems: &[
        taxon!(Subsystem, Scan),
        taxon!(Subsystem, Knowledge),
        taxon!(Subsystem, Work),
    ],
    context: r"
        Реестр входит в продукт крейтом документов, и код, порождённый сканом и
        макросами регистрации, компилируется под lints этого крейта. Продукты
        со строгой планкой включают на всё рабочее пространство запрет
        недокументированного публичного API, лишних квалификаций путей и
        замечаний clippy pedantic. Lints рабочего пространства Slipway этого не
        требовали, и порождённый код их не проходил.

        Замер на реестрах Slipway под таким профилем: без документации —
        порождённые модули документов, константы-ссылки и списки, статики
        макросов регистрации и значения таксономии; в свёртке журнала — 70
        лишних квалификаций crate::. Сбой виден только при внедрении, когда
        починить его может лишь автор Slipway.

        Рассматривались: allow в порождённом коде — у продукта с forbid это
        ошибка компиляции, а у остальных прячет то, что продукт требует;
        исключение крейта документов из lints продукта — цена переходит к
        каждому внедряющему, а реестр выходит из-под его правил; doc(hidden)
        на порождённом — missing_docs замолкает, но реестр исчезает из rustdoc,
        где его читают.
    ",
    decision: r"
        Порождённый сканом код и макросы регистрации документируют каждый
        публичный элемент и не глушат lints профиля. allow в порождённом коде
        остаётся только для правил именования и неиспользуемого импорта в
        пустом реестре. Порождённые файлы ссылаются друг на друга путями без
        crate::: они включаются рядом, и префикс лишний, а при включении в
        подмодуль — неверен.

        Профиль: из rustc — missing_docs, missing_debug_implementations,
        unreachable_pub, elided_lifetimes_in_paths, trivial_casts,
        trivial_numeric_casts, unused_qualifications, unused_lifetimes,
        single_use_lifetimes; из clippy — группа pedantic; из rustdoc —
        broken_intra_doc_links, private_intra_doc_links, unescaped_backticks.

        Профиль держит калитка Slipway. Крейт документов doc/ и демо-реестр
        examples/demo-doc объявляют его своими lints на уровне forbid, шаги
        clippy и doc калитки их собирают. forbid строже, чем нужно продукту:
        он ловит и попытку заглушить lint профиля. Вместе два реестра
        задействуют все эмиттеры — решения, спецификации, план, журнал,
        разметку кода — и таксономию.
    ",
    trade_offs: &[
        "Плюс: крейт документов входит в строгий продукт без исключений из его lints",
        "Плюс: регрессия порождённого кода — отказ калитки Slipway, а не находка при внедрении",
        "Плюс: у каждого модуля и ссылки реестра есть строка в rustdoc",
        "Минус: документация порождённого — шаблон с номером документа, а не его заголовок",
        "Минус: профиль повторён в двух манифестах — Cargo не соединяет lints рабочего пространства с добавками",
        "Минус: lints вне профиля — группа restriction clippy и собственные lints продукта — не проверяются",
    ],
    constraints: &[
        "Новый эмиттер или макрос регистрации задействуется реестром под профилем в той же работе.",
        "Профиль меняется в обоих манифестах реестров одним коммитом.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0001, crate::rfc::r0002],
);
