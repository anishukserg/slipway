slipway_knowledge::adr!(15,
    title: "Журнал работы: событие — файл плоского TOML, свёртка при сборке реестра, доказательство по хэшу дерева без журнала",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Work), taxon!(Subsystem, Cli)],
    context: r#"
        Инварианты 2 и 3 требуют, чтобы готовность имела доказательство на том
        же дереве, а состояние было историей, а не полем. Журнала не было:
        состояние восстанавливалось догадкой по трейлерам git, а правило «не
        больше пяти работ на срез» не отличало сделанное от начатого.
        Спецификация слоя работы задаёт каталог журнала с событиями в TOML по
        файлу на событие; решение 2 оставляет журнал в TOML, потому что его
        пишет машина.

        Рассматривались: свёртка только инструментом — проще, но неверное
        событие компилируется; события, дописываемые хуками в собственный
        коммит, — хрупко при коммите с временным индексом; доказательства
        только из CI — инвариант 2 оставался бы нормой без исполнителя;
        расширенный набор событий с блокировкой и повторным открытием — поля
        без механизма, который их читает.
    "#,
    decision: r#"
        Событие — файл doc/journal/<wNNNN|sNNNN>/<ГГГГММДДTЧЧММССZ>-<событие>.toml.
        Поля: event, work или slice, at; у gate — gate, tree, verdict; у
        landed — commit, tree и необязательное evidence = "history"; у
        abandoned — reason; у closed — ничего сверх общих. Формат — плоское
        подмножество TOML: пары ключ = "строка" и комментарии. Файл события не
        изменяется и не удаляется после коммита.

        Разбор и автомат — крейт slipway-journal без зависимостей. Его
        подключают скан при сборке реестра и инструмент; slipway-cli получает
        эту зависимость по этому решению.

        Автомат работы: без событий → started → landed или abandoned; gate
        допустим только у начатой работы; landed требует события gate с тем же
        деревом; landed с evidence = "history" допустим только у работы без
        событий и восстанавливает прошлое по трейлерам истории; после landed и
        abandoned событий нет. Срез закрывается событием closed один раз, и
        незавершённая работа в закрытом срезе — ошибка.

        Свёртка выполняется при сборке крейта документов. Нарушение автомата —
        ошибка компиляции с именем файла события; событие о работе или срезе
        вне плана — неразрешимый путь; незавершённая работа в закрытом срезе —
        ошибка вычисления константы. Состояние доступно как WORK_STATES и
        CLOSED_SLICES.

        Доказательство привязано к хэшу дерева без каталога журнала: git-хэш
        списка git ls-tree -r этого дерева. pre-commit после прохождения
        калитки сохраняет доказательство для хэша дерева коммита. Команды work
        и slice пишут события и коммитят их; коммит, меняющий только журнал,
        переиспользует доказательство того же дерева. Калитка отвергает
        изменение и удаление файлов журнала и приземление, чей коммит
        отсутствует или чьё дерево расходится с событием. Коммит, основанием
        которого служит срез, несёт трейлер Slipway-Slice: sNNNN — это
        дополняет решение 8.
    "#,
    trade_offs: &[
        "Плюс: состояние выводится из истории, статусного поля нет",
        "Плюс: неверное событие не собирается, и сообщение называет файл события",
        "Плюс: один автомат переходов для сборки и для инструмента",
        "Минус: коммит журнала пересобирает крейт документов",
        "Минус: без CI доказательство пишет локальный хук, а событие вручную может записать любой с правом записи",
        "Минус: подмножество строже TOML — событие с таблицами или числами отвергается",
        "Минус: прошлые работы восстановлены из трейлеров истории без доказательства",
    ],
    constraints: &[
        "Файл события журнала не изменяется и не удаляется после коммита.",
        "Журнал не переводится в Rust (решение 2): порождённый код — свёртка, а не носитель.",
        "Поле события появляется вместе с механизмом, который его читает (решение 5).",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002],
);
