slipway_knowledge::adr!(13,
    title: "Зависимости проверяются cargo-deny: лицензии, уязвимости, дубли, источники",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r#"
        Крейты Slipway подключают продукты, и каждая внешняя зависимость
        методологии становится зависимостью продукта — с её лицензией,
        уязвимостями и источником. До решения это ничем не проверялось.

        Первый прогон cargo-deny на рабочем пространстве: уязвимостей нет,
        лицензии — MIT, Apache-2.0 и Unicode-3.0, источник — только crates.io.
        Отказ — у публикуемых крейтов path-зависимости без версии, которые
        crates.io не примет.

        Рассматривались cargo-audit — только уязвимости — и cargo-vet — ручной
        аудит каждой версии, несоразмерный пяти внешним зависимостям.
    "#,
    decision: r#"
        Политика зависимостей записана в deny.toml корня: разрешённые лицензии
        перечислены явно; уязвимые и отозванные версии запрещены; две версии
        одного крейта запрещены; зависимость без версии разрешена только
        непубликуемым крейтам; источник — только crates.io.

        Калитка коммита проверяет политику по сохранённой базе уязвимостей без
        сети: коммит не зависит от доступности сети и проверяет то дерево,
        которое уходит в историю. Хук pre-push обновляет базу и проверяет по
        ней выгруженное дерево публикуемой вершины.

        Крейты документов и демо не публикуются; зависимости между
        библиотеками методологии несут версию.
    "#,
    trade_offs: &[
        "Плюс: чужая лицензия, уязвимость или источник новой зависимости — отказ коммита, а не находка при внедрении в продукт",
        "Плюс: коммит не зависит от сети — проверка идёт по сохранённой базе",
        "Минус: уязвимость, опубликованная после последнего обновления базы, не видна калитке коммита; её видит pre-push",
        "Минус: запрет двух версий одного крейта может заставить ждать, пока зависимости сойдутся на одной версии",
        "Минус: cargo-deny ставится отдельно, и его отсутствие — отказ калитки",
    ],
    constraints: &[
        "Новая лицензия в списке разрешённых — изменение политики отдельным коммитом с основанием из плана.",
        "Без сохранённой базы уязвимостей калитка отказывает; база ставится командой cargo deny fetch.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002],
);
