use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(1,
    title: "Ссылка между документами — путь к константе, а не число",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Knowledge), taxon!(Subsystem, Scan)],
    context: r"
        Первая редакция связывала документ с кодом через inventory: атрибут
        разметки порождал регистрацию, а валидатор в build.rs читал реестр
        через inventory::iter. Схема не работает: build.rs компилируется в
        отдельный бинарник, куда продуктовые крейты не слинкованы, поэтому
        реестр там всегда пуст и КАЖДАЯ ссылка даёт ошибку.

        Обнаружено двумя независимыми ревьюерами 2026-09-10. Дополнительно
        у схемы было ограничение: порождаемая регистрация — свободный item,
        поэтому разметку нельзя было ставить на методы внутри impl.
    ",
    decision: r"
        Скан исходников порождает модуль констант, по одной на документ и на
        размеченный фрагмент. Ссылка раскрывается в ПУТЬ к константе, а не в
        строковый литерал. Исчезновение документа или разметки делает путь
        неразрешимым — обычная ошибка компилятора E0425 с подсказкой.

        Атрибут разметки становится чистым маркером и возвращает элемент без
        изменений, поэтому применим где угодно, включая методы в impl.
    ",
    trade_offs: &[
        "Плюс: compile-time гарантия сохранена без inventory",
        "Плюс: разметка применима к любым элементам",
        "Минус: гарантия держится, пока скан свеж — нужна проверка свежести в CI",
        "Минус: разметка внутри отключённого условной компиляцией кода видна скану, но не компилятору",
    ],
    constraints: &[
        "Ссылка между документами не может быть числом или строкой.",
        "Скан работает с текстом файлов, а не со скомпилированным крейтом.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[],
);
