use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(14,
    title: "Правила коммитов, калитка и хуки — инструмент на Rust без зависимостей, по соглашениям",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r#"
        Правила коммитов, калитка и хуки были скриптами bash, и на них уже
        случилось три отказа окружения: TMPDIR увёл сборку в чужой проект,
        переменные git хука протекли во временный репозиторий и испортили
        индекс коммита, фильтр путей молча оставил шаг калитки без предмета.
        Самотест из двадцати сценариев и bash -n проверяли сценарий, а не
        тестируемый код. Пути реестра зашиты в скрипты, поэтому применить
        правила в другом проекте можно только копированием с правкой.

        Рассматривались: shellcheck поверх bash — статический анализ, но
        сценарий остаётся непереносимым; настройка путей в slipway.toml или в
        метаданных Cargo.toml — нужен парсер и около десятка зависимостей под
        политику решения 13; установленный бинарь в хуках самого Slipway —
        быстрее, но версия инструмента расходится с правилами в коммите.
    "#,
    decision: r#"
        Правила коммитов, калитка и хуки — крейт slipway-cli с бинарём
        cargo-slipway: команды commit, msg-check, gate, hook и hooks install.
        У крейта нет зависимостей: хук собирает инструмент, и сборка не тянет
        граф крейтов.

        Инструмент опирается на соглашения, а не на настройку: таксономия —
        doc/taxonomy.rs, работы — doc/work/ (решение 11), политика зависимостей
        — deny.toml, минимальная версия — rust-version корневого манифеста, хуки
        — .githooks/. Пути соглашений собраны в одном модуле. Настройка
        появится, когда пилот покажет проект, которому соглашения не подходят.

        В Slipway хуки — однострочники, которые запускают инструмент из рабочего
        дерева через cargo run, а калитку pre-commit собирает и запускает из
        выгруженного дерева коммита: изменение правил проверяется самими
        изменёнными правилами. Продукт ставит инструмент с закреплённой версией.

        Сценарии самотеста — интеграционные тесты крейта на временных
        репозиториях в каталоге сборки, а не в TMPDIR; дочерний git в них
        запускается без переменных GIT_*. Калитка гоняет их на каждом коммите
        вместе с остальными тестами.

        Блокировка коммита — файл, создаваемый атомарно, с номером процесса
        внутри; блокировку умершего процесса снимает ожидающий. File::lock
        стабилен с Rust 1.89, а крейт собирается и на минимальной версии 1.83.
    "#,
    trade_offs: &[
        "Плюс: правила — Rust-код под clippy, тестами и сборкой на минимальной версии",
        "Плюс: другой проект применяет правила установкой инструмента, без копирования скриптов",
        "Плюс: сценарии бывшего самотеста выполняются на каждом коммите, а не только при правке правил",
        "Минус: первый коммит на чистой машине ждёт сборки инструмента",
        "Минус: соглашения жёсткие — проект с другой раскладкой документов инструмент пока не поддерживает",
        "Минус: снятие блокировки умершего процесса опирается на /proc; без него блокировка ждёт тайм-аута, а два ожидающих могут снять одну блокировку одновременно",
    ],
    constraints: &[
        "Новая зависимость slipway-cli — отдельное решение: инструмент собирается внутри хука.",
        "Временные репозитории тестов не создаются в TMPDIR, и дочерний git в них не наследует переменные GIT_*.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 11),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::r0002, crate::rfc::r0003],
);
