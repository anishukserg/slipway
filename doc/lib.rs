//! Документы самого Slipway: решения, спецификации и план работ.
//!
//! Методология, применённая к себе: решения о том, как устроен Slipway, и
//! работа над ним ведутся по правилам Slipway. Это первое её испытание — и
//! первое место, где несоблюдение собственных правил стало бы видно
//! немедленно.
//!
//! Все типы документов лежат в одном крейте (решение 11): `adr/`, `rfc/`,
//! `thrust/`, `slice/`, `work/` и таксономия. Внутри крейта документы
//! ссылаются друг на друга путями `crate::`. Знание и план разделяет схема,
//! а не граф крейтов: в решении нет поля для ссылки на работу.
//!
//! Правило плана (решение 5): единицы работы заводятся только на текущие
//! срезы, не больше пяти на срез. Состояния у записей нет: по инварианту 3
//! состояние — свёртка журнала. Журнала пока нет (работа 5), и до него
//! сделанное восстанавливается из истории git по трейлеру
//! `Slipway-Work: w0001` в сообщении коммита.

pub mod taxonomy;

// Порождаются build.rs: модули документов, константы ссылок, списки и
// константные проверки классификации.
include!(concat!(env!("OUT_DIR"), "/adr.rs"));
include!(concat!(env!("OUT_DIR"), "/rfc.rs"));
include!(concat!(env!("OUT_DIR"), "/plan.rs"));

#[cfg(test)]
mod tests {
    use super::*;

    /// Непустота авторов и инвариантов обеспечена типом; здесь проверяется
    /// только то, чего тип не выражает: реестры не пусты, у записей есть
    /// заголовки.
    #[test]
    fn registries_are_not_empty() {
        assert!(!ALL.is_empty(), "реестр решений пуст");
        assert!(!ALL_SPECS.is_empty(), "реестр спецификаций пуст");
        for d in ALL {
            assert!(!d.title.trim().is_empty(), "решение {} без заголовка", d.id);
        }
        for s in ALL_SPECS {
            assert!(
                !s.title.trim().is_empty(),
                "спецификация {} без заголовка",
                s.id
            );
        }
    }

    /// Не больше пяти единиц работы на срез. Сила — по требованию: это тест,
    /// а не тип, и держится он тем, что тесты запускают.
    #[test]
    fn work_is_planned_within_wip() {
        for s in ALL_SLICES {
            let n = ALL_WORK.iter().filter(|w| w.slice.index() == s.id).count();
            assert!(
                n <= 5,
                "срез «{}» несёт {n} единиц работы",
                s.title.as_str()
            );
        }
    }
}
